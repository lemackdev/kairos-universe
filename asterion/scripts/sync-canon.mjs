// Copies the small set of confirmed canon fields Asterion displays into a checked-in
// snapshot, so the site deploys on its own without the rest of the repository.
// Run from /asterion: npm run canon:sync
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoData = path.resolve(here, "..", "..", "data", "organizations");
const target = path.resolve(here, "..", "src", "content", "canon-snapshot.json");

export function buildSnapshot(asterion, kairos) {
  return {
    source: {
      files: [
        "data/organizations/asterion-intelligence.json",
        "data/organizations/kairos-esports.json",
      ],
      note: "Generated by scripts/sync-canon.mjs. Do not edit by hand.",
    },
    asterion: {
      id: asterion.id,
      name: asterion.name,
      type: asterion.type,
      status: asterion.status,
      founderName: asterion.founder.realName,
      founderCommonName: asterion.founder.commonName,
      chiefExecutiveName: asterion.chiefExecutive.commonName,
      chiefExecutiveTitle: asterion.chiefExecutive.title,
      headquarters: asterion.headquarters,
      subsidiaries: asterion.subsidiaries,
      description: asterion.description,
      confirmedFacts: asterion.confirmedFacts,
      unconfirmedDetails: asterion.unconfirmedDetails,
    },
    kairos: {
      id: kairos.id,
      name: kairos.name,
      status: kairos.status,
      ownerName: kairos.owner.commonName,
      parentName: kairos.parentOrganization.name,
      headquarters: kairos.headquarters,
      divisions: kairos.divisions.map((d) => ({ id: d.id, name: d.name, status: d.status })),
      currentStoryPeriod: kairos.currentStoryPeriod.displayName,
      officialDebutPeriod: {
        leagueOfLegends: kairos.officialDebutPeriod.leagueOfLegends,
        counterStrike: kairos.officialDebutPeriod.counterStrike,
      },
      philosophy: kairos.philosophy,
    },
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const read = (name) => JSON.parse(fs.readFileSync(path.join(repoData, name), "utf8"));
  const snapshot = buildSnapshot(read("asterion-intelligence.json"), read("kairos-esports.json"));
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, `${JSON.stringify(snapshot, null, 2)}\n`);
  console.log(`Wrote ${path.relative(process.cwd(), target)}`);
}
